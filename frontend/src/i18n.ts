export type Lang = 'de' | 'en';

export const languages: {id: Lang; label: string; locale: string}[] = [
  {id: 'de', label: 'Deutsch', locale: 'de-DE'},
  {id: 'en', label: 'English', locale: 'en-GB'},
];

const storageKey = 'liforra-tool.lang';
const dictionaries: Record<Lang, Record<Key, string>> = {de, en};

function loadLang(): Lang {
  try {
    const stored = localStorage.getItem(storageKey);
    if (stored === 'de' || stored === 'en') return stored;
  } catch {
    // storage unavailable — fall back to German
  }
  return 'de';
}

let current: Lang = loadLang();
const listeners = new Set<() => void>();

export function getLang(): Lang {
  return current;
}

export function locale(): string {
  return languages.find((l) => l.id === current)!.locale;
}

export function setLang(lang: Lang) {
  if (lang === current) return;
  current = lang;
  try {
    localStorage.setItem(storageKey, lang);
  } catch {
    // not persisted; still applies for this session
  }
  document.documentElement.lang = lang;
  listeners.forEach((cb) => cb());
}

export function onLanguageChange(cb: () => void) {
  listeners.add(cb);
}

export function t(key: Key, params?: Record<string, string | number>): string {
  let text = dictionaries[current][key];
  if (params) for (const [k, v] of Object.entries(params)) text = text.split(`{${k}}`).join(String(v));
  return text;
}

document.documentElement.lang = current;
